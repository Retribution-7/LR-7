import { clsx, type ClassValue } from 'clsx';
import { twMerge } from 'tailwind-merge';

export const cn = (...inputs: ClassValue[]) => twMerge(clsx(inputs));

export function formatDate(iso?: string | null) {
  if (!iso) return '—';
  const [y, m, d] = iso.slice(0, 10).split('-');
  return `${d}.${m}.${y}`;
}

export const toInputDate = (iso: string) => iso.slice(0, 10);

export function formatNumber(n: number, digits = 2) {
  return n.toLocaleString('ru-RU', { minimumFractionDigits: 0, maximumFractionDigits: digits });
}

export function ageFrom(iso: string) {
  const b = new Date(iso);
  const now = new Date();
  let age = now.getUTCFullYear() - b.getUTCFullYear();
  const m = now.getUTCMonth() - b.getUTCMonth();
  if (m < 0 || (m === 0 && now.getUTCDate() < b.getUTCDate())) age--;
  return age;
}

